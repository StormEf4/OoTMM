import math, sys
from PIL import Image, ImageDraw

S = 32
SS = 8  # supersample
W = S * SS

BODY = (150, 80, 210, 255)
BODY_DARK = (105, 50, 160, 255)
BELLY = (245, 175, 230, 255)
EAR_IN = (255, 150, 210, 255)
WHITE = (255, 255, 255, 255)
PUPIL = (30, 25, 60, 255)
IRIS = (90, 170, 255, 255)
BEAK = (255, 160, 40, 255)
BEAK_DARK = (210, 110, 20, 255)
OUTLINE = (55, 20, 85, 255)

img = Image.new('RGBA', (W, W), (0, 0, 0, 0))
d = ImageDraw.Draw(img)
def e(cx, cy, rx, ry, col):
    d.ellipse([(cx - rx) * SS, (cy - ry) * SS, (cx + rx) * SS, (cy + ry) * SS], fill=col)
def poly(pts, col):
    d.polygon([(x * SS, y * SS) for x, y in pts], fill=col)

# ears (outline then fill)
for sx in (-1, 1):
    poly([(16 + sx * 5, 12), (16 + sx * 13.5, 0.5), (16 + sx * 10, 13)], OUTLINE)
    poly([(16 + sx * 5.8, 11.5), (16 + sx * 12.6, 2), (16 + sx * 9.6, 12)], BODY)
    poly([(16 + sx * 7, 10.5), (16 + sx * 11.6, 4), (16 + sx * 9.4, 11)], EAR_IN)
# tuft
poly([(14.5, 6), (16, 1.5), (17.5, 6)], OUTLINE)
poly([(15.2, 6), (16, 2.8), (16.8, 6)], BODY_DARK)
# body
e(16, 18.5, 12.5, 12.5, OUTLINE)
e(16, 18.5, 11.5, 11.5, BODY)
# belly
e(16, 24, 7.5, 6.5, BELLY)
# eyes
for sx in (-1, 1):
    cx = 16 + sx * 5
    e(cx, 15.5, 4.6, 5.0, OUTLINE)
    e(cx, 15.5, 3.8, 4.3, WHITE)
    e(cx + sx * -0.3, 16.2, 2.6, 3.0, IRIS)
    e(cx + sx * -0.3, 16.4, 1.7, 2.1, PUPIL)
    e(cx + sx * -0.3 - 0.8, 15.0, 0.8, 0.8, WHITE)
    # eyelid
    d.chord([(cx - 4.6) * SS, (15.5 - 5.0) * SS, (cx + 4.6) * SS, (15.5 + 5.0) * SS], 200, 340, fill=BODY_DARK)
# beak
poly([(13.2, 20), (18.8, 20), (16, 23.6)], BEAK_DARK)
poly([(13.8, 20), (18.2, 20), (16, 22.6)], BEAK)
# feet
for sx in (-1, 1):
    e(16 + sx * 5, 30.3, 3.6, 1.5, BEAK_DARK)
    e(16 + sx * 5, 30.0, 3.0, 1.1, BEAK)

small = img.resize((S, S), Image.LANCZOS)
small.save(sys.argv[1])
small.resize((S * 10, S * 10), Image.NEAREST).save(sys.argv[2])

# RGBA5551 C array
px = small.load()
vals = []
for y in range(S):
    for x in range(S):
        r, g, b, a = px[x, y]
        v = ((r >> 3) << 11) | ((g >> 3) << 6) | ((b >> 3) << 1) | (1 if a >= 128 else 0)
        if a < 128:
            v = 0
        vals.append(v)
with open(sys.argv[3], 'w') as f:
    f.write('/* Generated by docs/custom/tools/furby.py: 32x32 RGBA16 Furby sprite */\n')
    for i in range(0, len(vals), 8):
        f.write('    ' + ', '.join('0x%04x' % v for v in vals[i:i + 8]) + ',\n')

# Glow: 32x32 I8 soft radial falloff
vals = []
for y in range(S):
    for x in range(S):
        dx = (x + 0.5 - S / 2) / (S / 2)
        dy = (y + 0.5 - S / 2) / (S / 2)
        r = math.sqrt(dx * dx + dy * dy)
        v = max(0.0, 1.0 - r)
        vals.append(int(round(255 * (v ** 1.6))))
with open(sys.argv[4], 'w') as f:
    f.write('/* Generated by docs/custom/tools/furby.py: 32x32 I8 fairy glow */\n')
    for i in range(0, len(vals), 16):
        f.write('    ' + ', '.join('0x%02x' % v for v in vals[i:i + 16]) + ',\n')
